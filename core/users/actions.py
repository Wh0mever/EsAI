from __future__ import annotations

import os
import uuid
import logging
from decimal import Decimal
from django.contrib import admin
from django.utils import timezone
from payments.freedompay import charge_recurring_by_user_token, FreedomPayError
from plans.models import UserSubscription, SubscriptionStatus

logger = logging.getLogger("payments")


def _price_to_int(val) -> int:
    try:
        return int(Decimal(str(val)).quantize(Decimal("1")))
    except Exception:
        try:
            return int(val)
        except Exception:
            return 0


@admin.action(description="Списать по текущему тарифу (FreedomPay)")
def charge_by_current_plan(modeladmin, request, queryset):
    """Admin action: charge selected users according to their active subscription plan price.

    - Uses the user's ACTIVE subscription (most recent) and its Plan.price_amount.
    - Skips users without an active paid plan or without a saved token.
    - Currency: FREEDOM_PAY_DEFAULT_CURRENCY env or KGS.
    - Order ID autogenerated per user.
    """
    currency = os.environ.get("FREEDOM_PAY_DEFAULT_CURRENCY", "KGS").upper()
    actor_id = getattr(request.user, "id", None)

    ok = 0
    failed = 0
    notes: list[str] = []

    for u in queryset:
        sub: UserSubscription | None = (
            UserSubscription.objects.select_related("plan")
            .filter(user=u, status=SubscriptionStatus.ACTIVE)
            .order_by("-start_date")
            .first()
        )
        if not sub:
            failed += 1
            notes.append(f"user {u.id}: no active subscription")
            continue

        plan = sub.plan
        amount = _price_to_int(getattr(plan, "price_amount", 0))
        if plan.is_free or amount <= 0:
            failed += 1
            notes.append(f"user {u.id}: free/zero plan")
            continue

        if not (u.pay_token or "").strip():
            failed += 1
            notes.append(f"user {u.id}: no token")
            continue

        order_id = f"admin-sub-{sub.id}-{uuid.uuid4().hex[:8]}"
        description = f"Admin charge for plan #{plan.id}"

        logger.info(
            "charge_attempt actor=%s target=%s order_id=%s amount=%s %s",
            actor_id,
            u.id,
            order_id,
            amount,
            currency,
        )
        try:
            resp = charge_recurring_by_user_token(
                user=u,
                amount=amount,
                currency=currency,
                order_id=order_id,
                description=description,
                fp_user={"email": u.email or "", "phone": u.tel or ""},
            )
        except FreedomPayError as e:
            failed += 1
            logger.error(
                "charge_error actor=%s target=%s order_id=%s error=%s",
                actor_id,
                u.id,
                order_id,
                str(e),
            )
            notes.append(f"user {u.id}: {e}")
            continue
        except Exception as e:
            failed += 1
            logger.exception(
                "charge_exception actor=%s target=%s order_id=%s",
                actor_id,
                u.id,
                order_id,
            )
            notes.append(f"user {u.id}: {e}")
            continue

        ok += 1
        logger.info(
            "charge_success actor=%s target=%s order_id=%s amount=%s %s data=%s",
            actor_id,
            u.id,
            order_id,
            amount,
            currency,
            resp,
        )

    summary = f"Успешно: {ok}; Ошибок: {failed}"
    if notes:
        summary += "; " + "; ".join(notes[:5])
        if len(notes) > 5:
            summary += f" (+ еще {len(notes) - 5})"
    try:
        modeladmin.message_user(request, summary)
    except Exception:
        pass
