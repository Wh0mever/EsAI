export type ComposerTextKey = keyof typeof COMPOSER_RU;

type Translate = TFunction | ((key: string, options?: Record<string, unknown>) => unknown);

/** t(key) с русским по умолчанию из COMPOSER_RU. */
export function ct(t: Translate, key: ComposerTextKey, params?: Record<string, unknown>): string {
  const fn = t as (key: string, options?: Record<string, unknown>) => unknown;
  const out = fn(key, { ns: "vstudio", defaultValue: COMPOSER_RU[key], ...(params || {}) });
  return typeof out === "string" ? out : String(out ?? "");
}

/** Русский без i18next (тесты, запасной текст). */
export function ruText(key: ComposerTextKey, params?: Record<string, unknown>): string {
  return COMPOSER_RU[key].replace(/\{\{\s*(\w+)\s*\}\}/g, (_, k: string) => String(params?.[k] ?? ""));
}
