/**
 * Сценарии первого экрана («С чего начать»): клик кладёт заготовку запроса в
 * композер — ничего не запускает и не тратит. Тексты переводятся ключами
 * `home.tpl.<id>.label|prompt` (ns vstudio), русский здесь — defaultValue.
 *
 * Слова в квадратных скобках оставлены намеренно: это места, куда человек
 * вписывает своё — героя, товар, место. Заготовка показывает порядок, который
 * лучше всего понимают модели: кто → что делает → где → камера → свет.
 *
 * Своё фото и логотип — такие же места в скобках. Просьбы к человеку («добавьте
 * фото через @») в заготовке быть не должно: она уходит модели слово в слово.
 * И знака @ тоже: редактор принимает его за начало отметки и, получив текст с
 * @ на конце, сам открывает список материалов поверх только что вписанного.
 *
 * Четыре примера пустого проекта (feed/examples.ts, VS_EXAMPLES) — отдельный
 * список: там готовые сцены, здесь — жанры с пропусками.
 */
import type { VsKind } from "@/lib/vstudio/types";

export type VsTemplateId = "film" | "product" | "ugc" | "clip" | "anime" | "photo" | "poster" | "logo";

export type VsTemplate = {
  id: VsTemplateId;
  kind: VsKind;
  /** Пропорция жанра; "auto" — как у фото или как выбрано у модели. */
  aspect: string;
  /** Подпись чипа (ru по умолчанию). */
  label: string;
  /** Заготовка запроса (ru по умолчанию). */
  prompt: string;
};

/**
 * Чем первый экран заполняет композер: вид, текст и пропорция. Пропорцию
 * композер берёт, только если выбранная модель её умеет (как у примеров).
 */
export type VsStarter = { kind: VsKind; text: string; aspect?: string | null };

