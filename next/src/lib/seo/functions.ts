export function getFunction(slug: string): SeoFunction | undefined {
  return SEO_FUNCTIONS.find((f) => f.slug === slug);
}

export function getRelatedFunctions(slug: string, count = 4): SeoFunction[] {
  return SEO_FUNCTIONS.filter((f) => f.slug !== slug).slice(0, count);
}
