export type Ct = (key: string, params?: Record<string, string | number>) => string;

/** Все русские тексты раздела: интерфейс + ошибки (эталон ru/creative.json). */
export const ALL_RU: Record<string, string> = { ...CREATIVE_TEXT_RU, ...ALL_ERROR_RU };

/** t пространства creative с русским текстом из таблиц по умолчанию. */
export function useCt(extra?: Record<string, string>): { ct: Ct; lang: string } {
  const { t, i18n } = useTranslation("creative");
  const ct = useCallback<Ct>(
    (key, params) => t(key, { defaultValue: extra?.[key] ?? ALL_RU[key] ?? key, ...(params || {}) }),
    [t, extra],
  );
  return { ct, lang: i18n.language || "ru" };
}
